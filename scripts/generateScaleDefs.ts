/**
 * Extrait les InterpretationRanges et subscales des fichiers TS source
 * et génère un fichier JS consommable par les Netlify Functions.
 *
 * Usage : npx tsx scripts/generateScaleDefs.ts
 */
import { ALL_SCALES } from '../src/data/scales/index';
import { DEFI_SCALE_CONFIG } from '../src/config/defiConfig';
import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

interface RangeDef {
  min: number;
  max: number;
  severity: string;
  alertLevel?: number;
}

interface SubscaleDef {
  key: string;
  label: string;
  range: { min: number; max: number };
  scoringMode: string;
}

interface ScaleDef {
  id: string;
  scoreRange: { min: number; max: number };
  scoringMode: string;
  ranges: RangeDef[];
  subscales: SubscaleDef[] | null;
}

const eligibleIds = Object.keys(DEFI_SCALE_CONFIG);
const defs: Record<string, ScaleDef> = {};

for (const id of eligibleIds) {
  const scale = ALL_SCALES.find(s => s.id === id);
  if (!scale) {
    console.warn(`[generateScaleDefs] Scale "${id}" in defiConfig but not in ALL_SCALES`);
    continue;
  }

  defs[id] = {
    id,
    scoreRange: scale.scoreRange,
    scoringMode: scale.scoringMode ?? 'sum',
    ranges: scale.interpretation.map(r => ({
      min: r.min,
      max: r.max,
      severity: r.severity,
      ...(r.alertLevel != null ? { alertLevel: r.alertLevel } : {}),
    })),
    subscales: scale.subscales?.map(sub => ({
      key: sub.key,
      label: sub.label,
      range: sub.range,
      scoringMode: sub.scoringMode ?? 'sum',
    })) ?? null,
  };
}

const outPath = path.resolve(__dirname, '../netlify/functions/_defi/scaleDefinitions.js');
const content = `// AUTO-GENERATED — do not edit manually.
// Source: scripts/generateScaleDefs.ts → src/data/scales/*.ts
// Regenerate: npx tsx scripts/generateScaleDefs.ts

const SCALE_DEFS = ${JSON.stringify(defs, null, 2)};

module.exports = { SCALE_DEFS };
`;

fs.writeFileSync(outPath, content, 'utf-8');
console.log(`✓ Generated ${Object.keys(defs).length} scale definitions → ${outPath}`);

// ── Also generate DEFI_SCALE_CONFIG for server ──────────────────────────────
const serverScales = Object.entries(DEFI_SCALE_CONFIG)
  .filter(([, v]) => v.public !== 'interdit' || v.intime !== 'interdit');

const configLines = serverScales.map(([k, v]) =>
  `  ${k.padEnd(20)}: { public: '${v.public}',${' '.repeat(Math.max(1, 10 - v.public.length))}intime: '${v.intime}' },`
);

const configOutPath = path.resolve(__dirname, '../netlify/functions/_defi/defiScaleConfig.generated.js');
const configContent = `// AUTO-GENERATED by scripts/generateScaleDefs.ts — DO NOT EDIT
// Source of truth: src/config/defiConfig.ts
const DEFI_SCALE_CONFIG = {
${configLines.join('\n')}
};

module.exports = { DEFI_SCALE_CONFIG };
`;

fs.writeFileSync(configOutPath, configContent, 'utf-8');
console.log(`✓ Generated ${serverScales.length} server scale configs → ${configOutPath}`);
